"""Write the hardware results the website shows: python hardware_runs/export_web.py → web/lib/hardware-data.js

Generated from the analysis files in hardware_runs/results; web/tests/hardware.test.js checks the
two stay in sync.
"""

from __future__ import annotations

import json
from pathlib import Path

R = Path(__file__).resolve().parent / "results"
OUT = Path(__file__).resolve().parents[1] / "web" / "lib" / "hardware-data.js"
load = lambda name: json.loads((R / name).read_text())  # noqa: E731
r4 = lambda x: None if x is None else round(float(x), 4)  # noqa: E731


def main():
    chsh = load("chsh-ibm_kingston-analysis.json")
    chsh_raw = load("chsh-ibm_kingston.json")
    sch = load("schwinger-run2-ibm_kingston-analysis.json")
    sch_raw = load("schwinger-run2-ibm_kingston.json")
    rb = load("rb-ibm_kingston-analysis.json")
    rb_raw = load("rb-run2-ibm_kingston.json")
    data = {
        "device": "ibm_kingston",
        "date": chsh_raw["submitted"][:10],
        "chsh": {"S": round(chsh["S"], 3), "S_err": round(chsh["S_err"], 3), "shots": chsh_raw["shots"], "qubits": chsh_raw["layout"], "job": chsh_raw["job_id"],
                 "sweep": sorted([[r4(s["angle_diff"]), r4(s["E"])] for s in chsh["sweep"]])},
        "schwinger": {"qubits": sch_raw["layout"], "shots": sch_raw["shots"], "job": sch_raw["job_id"], "scales": [1, 2, 3],
                      "rows": [{"t": r["t"], "exact": r4(r["exact"]), "raw": r4(r["raw"]), "mitigated": r4(r["readout_mitigated"]),
                                "mitigated_err": r4(r["readout_mitigated_err"]), "zne": r4(r["zne_linear"]), "zne_err": r4(r["zne_linear_err"])}
                               for r in sch["rows"]]},
        "rb": {"qubit": rb_raw["layout"][0], "r": r4(rb["error_per_clifford"] * 1e4), "r_err": r4(rb["error_per_clifford_err"] * 1e4),
               "A": r4(rb["A"]), "f": round(rb["f"], 7), "B": r4(rb["B"]), "jobs": [load("rb-run1-ibm_kingston.json")["job_id"], rb_raw["job_id"]],
               "points": [[p["m"], r4(p["survival"]), r4(p["sem"])] for p in rb["points"]]},
    }
    OUT.write_text(
        "// Results measured on IBM Quantum hardware (generated by hardware_runs/export_web.py from the\n"
        "// analysis files in hardware_runs/results; do not edit by hand). RB r and r_err are in units of 1e-4.\n\n"
        f"export const HARDWARE = {json.dumps(data, indent=1, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print("wrote", OUT)


if __name__ == "__main__":
    main()
